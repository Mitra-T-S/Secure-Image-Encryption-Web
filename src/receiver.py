# ──────────────────────────────────────────
# STEP 4 — REVERSE DIFFUSION LAYER
# ──────────────────────────────────────────
def reverse_diffusion(cipher_data, permutation, xor_key):
    """
    Reverses the secondary diffusion layer from sender Step 4.

    Sender applied:
      diffused = (cipher XOR xor_key)[permutation]

    To reverse:
      Step 1 — Compute inverse permutation
               inv_perm[permutation[i]] = i
      Step 2 — Apply inverse permutation to undo the shuffle
      Step 3 — XOR again with same key (XOR is its own inverse)
                 x XOR k XOR k = x
    """
    print("\n[STEP 4] Reversing Diffusion Layer...")

    # Inverse permutation
    inv_perm              = np.zeros_like(permutation)
    inv_perm[permutation] = np.arange(len(permutation))

    # Undo permutation, then undo XOR
    undiffused = (cipher_data[inv_perm]) ^ xor_key

    print(f"  Inverse permutation : applied")
    print(f"  XOR key reversed    : {xor_key}")
    return undiffused


# ──────────────────────────────────────────
# STEP 5 — 2D-LSCM CHAOTIC SEQUENCE
# ──────────────────────────────────────────
def generate_chaotic_sequence(T_matrix, length, mod=MOD):
    """
    Regenerates the exact same 2D-LSCM chaotic sequence
    that was used on the sender side.

    This works because:
      - Same T matrix → same trace(T) → same x0, y0 seeds
      - Same deterministic map formula → identical sequence

    2D-LSCM:
      x(n+1) = |sin(pi * mu * (y(n)+3) * x(n) * (1-x(n)))|
      y(n+1) = |sin(pi * mu * (x(n+1)+3) * y(n) * (1-y(n)))|
    """
    print("\n[STEP 5] Regenerating 2D-LSCM Chaotic Sequence...")

    trace_val = int(np.trace(T_matrix))
    x         = (trace_val % (mod - 1)) / mod
    y         = 1.0 - x

    print(f"  trace(T) = {trace_val}")
    print(f"  x seed   = {x:.6f}")
    print(f"  y seed   = {y:.6f}")

    chaos = []
    for _ in range(length):
        x = abs(math.sin(math.pi * MU * (y + 3) * x * (1 - x)))
        y = abs(math.sin(math.pi * MU * (x + 3) * y * (1 - y)))
        chaos.append((x + y) / 2.0)

    chaos_int = (np.array(chaos) * (mod - 1)).astype(int) % mod
    print(f"  Length   : {length}")
    print(f"  Sample   : {chaos_int[:5]}")
    return chaos_int


# ──────────────────────────────────────────
# MODULAR MATRIX INVERSE
# ──────────────────────────────────────────
def mod_matrix_inverse(T, mod=MOD):
    """
    Gauss-Jordan elimination in GF(mod).
    mod = 257 is prime → inverse always exists when diagonal != 0.
    """
    n   = T.shape[0]
    aug = np.hstack([T.astype(int) % mod, np.eye(n, dtype=int)])

    for col in range(n):
        pivot = int(aug[col, col]) % mod
        if pivot == 0:
            aug[col, col] = 1
            pivot         = 1
        p_inv    = pow(pivot, mod - 2, mod)
        aug[col] = (aug[col] * p_inv) % mod
        for row in range(n):
            if row != col:
                f        = int(aug[row, col]) % mod
                aug[row] = (aug[row] - f * aug[col]) % mod

    return aug[:, n:] % mod


# ──────────────────────────────────────────
# STEP 6 — INVERSE BIJECTIVE MAPPING
# ──────────────────────────────────────────
def bijective_decrypt(cipher_vector, chaotic_int, T_matrix, mod=MOD):
    """
    Reverses the bijective encryption formula.

    Sender applied:
      Q(a, b) = T^-1 (Ta + Tb)  mod 257

    To recover a (original pixels):
      T * Q = Ta + Tb          (multiply both sides by T)
      Ta    = T*Q - Tb         (subtract Tb)
      a     = T^-1 (T*Q - Tb)  (multiply by T^-1)

    So the inverse formula is:
      a = T^-1 ( T*Q - T*b )  mod 257
        = T^-1 * T * Q - b    mod 257
        = Q - b               mod 257

    Where:
      Q = encrypted block   (9 values)
      b = chaotic block     (9 values, same sequence as sender)
      T^-1 = modular inverse of T
    """
    print("\n[STEP 6] Inverse Bijective Mapping (Decryption)...")
    print("  Formula : a = T^-1(T*Q - T*b) mod 257")

    T_inv   = mod_matrix_inverse(T_matrix, mod)
    n       = len(cipher_vector)
    pad_len = (BLOCK_SIZE - n % BLOCK_SIZE) % BLOCK_SIZE
    q_pad   = np.pad(cipher_vector.astype(int), (0, pad_len))
    b_pad   = np.pad(chaotic_int,               (0, pad_len))
    output  = np.zeros(len(q_pad), dtype=int)

    for i in range(0, len(q_pad), BLOCK_SIZE):
        q_blk  = q_pad[i:i+BLOCK_SIZE]
        b_blk  = b_pad[i:i+BLOCK_SIZE]
        TQ     = (T_matrix @ q_blk) % mod
        Tb     = (T_matrix @ b_blk) % mod
        diff   = (TQ - Tb) % mod
        output[i:i+BLOCK_SIZE] = (T_inv @ diff) % mod

    recovered = output[:n].astype(np.uint8)
    print(f"  Decrypted (first 5) : {recovered[:5]}")
    return recovered


# ──────────────────────────────────────────
# STEP 7 — NPCR & UACI (VERIFICATION)
# ──────────────────────────────────────────
def compute_npcr_uaci(original, encrypted):
    """
    Computes NPCR and UACI between the encrypted image
    and the decrypted image.

    After correct decryption:
      NPCR should be ~0%   (decrypted == original → no pixels differ)
      UACI should be ~0%   (no intensity difference)

    This confirms the decryption was successful.
    """
    print("\n[STEP 7] NPCR & UACI Verification...")

    O    = original.astype(np.float64)
    E    = encrypted.astype(np.float64)

    npcr = (np.sum(O != E) / O.size) * 100.0
    uaci = (np.sum(np.abs(O - E) / 255.0) / O.size) * 100.0

    print(f"  NPCR (encrypted vs decrypted) : {npcr:.4f}%  (perfect = 0.0%)")
    print(f"  UACI (encrypted vs decrypted) : {uaci:.4f}%  (perfect = 0.0%)")

    if npcr == 0.0 and uaci == 0.0:
        print("  STATUS : PERFECT DECRYPTION — images are identical!")
    else:
        print("  STATUS : WARNING — decrypted image differs from original!")

    return npcr, uaci


