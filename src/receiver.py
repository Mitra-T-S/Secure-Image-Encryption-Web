# ──────────────────────────────────────────
# STEP 1 — LOAD KEY MATRIX
# ──────────────────────────────────────────
def load_key(mod=MOD) -> np.ndarray:
    """
    Loads the T matrix from key_matrix.pkl.
    This file was generated by sender.py and must be
    shared with the receiver via a secure channel.

    The T matrix is the root of all decryption:
      - Its trace seeds the 2D-LSCM chaotic sequence
      - T itself is used to recompute Ta and Tb
      - T^-1 is used in the inverse bijective mapping
    """
    print("\n[STEP 1] Loading Key Matrix...")
    if not os.path.exists(KEY_FILE):
        raise FileNotFoundError(
            f"Key file '{KEY_FILE}' not found!\n"
            "  Make sure key_matrix.pkl from the sender is in this folder."
        )
    with open(KEY_FILE, "rb") as f:
        T_matrix = pickle.load(f)

    if not (isinstance(T_matrix, np.ndarray) and T_matrix.shape == (9, 9)):
        raise ValueError("Invalid key file — expected 9x9 numpy array.")

    print(f"  T matrix loaded  : shape {T_matrix.shape}, mod {mod}")
    print(f"  Diagonal         : {np.diag(T_matrix)}")
    return T_matrix


# ──────────────────────────────────────────
# STEP 2 — LOAD ENCRYPTED PAYLOAD
